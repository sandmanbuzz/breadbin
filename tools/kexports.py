#!/usr/bin/env python3
"""Kernel exports for loadable modules.

    kexports.py src/kernel/kapi.inc build/kernel.lbl > build/kexp.s

Reads the names the kernel exports to modules (the .word list in kapi.inc, in order) and
their linked addresses (ld65 -Ln labels), and writes an assembler file that defines them as
absolute symbols, plus KHASH: the 16-bit sum of the addresses. A module is linked against
that file; mod_load in the kernel sums its own copy of the table and refuses a module whose
header hash differs (the module was built against another kernel).
"""
import re
import sys


def main(inc, lbl):
    names = []
    for line in open(inc):
        line = line.split(";")[0]
        m = re.match(r"\s*\.word\s+(.*)", line)
        if m:
            names += [n.strip() for n in m.group(1).split(",") if n.strip()]
    addr = {}
    for line in open(lbl):
        m = re.match(r"al ([0-9A-Fa-f]+) \.(\S+)", line)
        if m:
            addr[m.group(2)] = int(m.group(1), 16)
    missing = [n for n in names if n not in addr]
    if missing:
        sys.exit("kexports: not in the kernel labels: " + ", ".join(missing))
    total = sum(addr[n] for n in names) & 0xFFFF
    print("; generated by tools/kexports.py from kapi.inc and the kernel labels")
    print(".export " + ", ".join(names + ["KHASH"]))
    for n in names:
        print(f"{n} = ${addr[n]:04X}")
    print(f"KHASH = ${total:04X}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
