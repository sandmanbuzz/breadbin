#!/usr/bin/env python3
"""Export the kernel's module API (docs/design/next/modules-v1.md).

  kexports.py gen   KERNEL.LBL KAPI.TXT OUT_DIR   writes OUT_DIR/kexp.s, kexp.inc, khash.inc
  kexports.py check KERNEL.LBL KAPI.TXT HASH_INC  exit 1 unless khash.inc holds the hash of KERNEL.LBL

kexp.s    `.export NAME := $ADDR` (`.exportzp` below $100) plus KAPI_HASH, linked into every module
kexp.inc  the matching `.import`/`.importzp` lines, for the module sources
khash.inc `.word $HASH`, assembled into the kernel (src/kernel/khash.s)

The hash is a CRC-16 (CCITT, init $FFFF) over "NAME=ADDR\\n" for the whitelist in file order.
Errors (exit 1): a name missing from the label file, a name inside INIT (released after boot),
a duplicate, a name that is not a plain label (the __X__ linker symbols).
"""
import os
import re
import sys


class KapiError(Exception):
    pass


def parse_labels(text):
    syms = {}
    for line in text.splitlines():
        m = re.match(r"al ([0-9A-Fa-f]+) \.(\S+)$", line.strip())
        if m:
            syms[m.group(2)] = int(m.group(1), 16)
    return syms


def parse_whitelist(text):
    names = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    return names


def crc16(data, crc=0xFFFF):
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def resolve(syms, names):
    """-> [(name, addr)] in whitelist order, or KapiError."""
    init_lo = syms.get("__INIT_RUN__")
    init_hi = None if init_lo is None else init_lo + syms.get("__INIT_SIZE__", 0)
    seen, out = set(), []
    for n in names:
        if n in seen:
            raise KapiError(f"duplicate: {n}")
        seen.add(n)
        if n.startswith("__") and n.endswith("__"):
            raise KapiError(f"not a plain label: {n}")
        if n not in syms:
            raise KapiError(f"not in the kernel label file: {n}")
        a = syms[n]
        if init_lo is not None and init_lo <= a < init_hi:
            raise KapiError(f"{n} (${a:04X}) is in INIT, which is released after boot")
        out.append((n, a))
    return out


def api_hash(pairs):
    return crc16("".join(f"{n}={a:04X}\n" for n, a in pairs).encode())


def render(pairs):
    h = api_hash(pairs)
    s = ["; generated by tools/kexports.py: do not edit"]
    inc = ["; generated by tools/kexports.py: do not edit"]
    for n, a in pairs:
        if a < 0x100:
            s.append(f".exportzp {n} := ${a:02X}")
            inc.append(f".importzp {n}")
        else:
            s.append(f".export {n} := ${a:04X}")
            inc.append(f".import {n}")
    s.append(f".export KAPI_HASH := ${h:04X}")
    inc.append(".import KAPI_HASH")
    return "\n".join(s) + "\n", "\n".join(inc) + "\n", f"; generated by tools/kexports.py\n.word ${h:04X}\n", h


def main(argv):
    if len(argv) != 5 or argv[1] not in ("gen", "check"):
        print(__doc__, file=sys.stderr)
        return 2
    cmd, lbl, kapi, third = argv[1:]
    try:
        pairs = resolve(parse_labels(open(lbl).read()), parse_whitelist(open(kapi).read()))
    except KapiError as e:
        print(f"kexports: {e}", file=sys.stderr)
        return 1
    s, inc, hinc, h = render(pairs)
    if cmd == "gen":
        os.makedirs(third, exist_ok=True)
        for name, body in (("kexp.s", s), ("kexp.inc", inc), ("khash.inc", hinc)):
            p = os.path.join(third, name)
            if not os.path.exists(p) or open(p).read() != body:   # keep mtimes when nothing changed
                open(p, "w").write(body)
        print(f"kexports: {len(pairs)} symbols, hash ${h:04X}")
        return 0
    have = open(third).read() if os.path.exists(third) else ""
    if have != hinc:
        print(f"kexports: {third} does not hold ${h:04X}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
